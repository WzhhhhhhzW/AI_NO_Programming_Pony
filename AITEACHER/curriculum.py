TOTAL = len(LESSONS)


def get_lesson(index: int) -> dict:
    """按下标取课程，越界自动夹紧。"""
    return LESSONS[clamp(index)]


def clamp(index: int) -> int:
    if index < 0:
        return 0
    if index >= TOTAL:
        return TOTAL - 1
    return index
